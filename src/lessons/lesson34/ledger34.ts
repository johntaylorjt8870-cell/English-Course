/**
 * عدد الأقسام المرقّمة وعدد أقسام السجل الكلية.
 * ملاحظة توثيق: المصدر ينطق أقسامه مرقّمةً بالعربية من «2» إلى «39»،
 * ويرمز لها بالأرقام المحاطة بدائرة ①…㉟ ثم ㊱…㊳ — أي أن الرمز ㊰
 * (القسم 36) غير مستخدم في المصدر نفسه، فيكون عدد الأقسام المرقّمة 38
 * لا 39. السجل يحفظ هذا الترقيم كما ورد حرفيًا دون إعادة ترقيم.
 */
export const SOURCE_NUMBERED_COUNT_34 = SOURCE_SECTIONS_34.filter((c) => c.roman).length;
export const SOURCE_LEDGER_COUNT_34 = SOURCE_SECTIONS_34.length;

/** نص السجل كاملًا كسلسلة واحدة — لتدقيق الوجود النصي */
export const LEDGER_TEXT_34 = SOURCE_SECTIONS_34.map((c) => c.title + "\n" + c.units.join("\n")).join("\n");

export function getSourceSection34(id: SourceOrder34) {
  const sec = SOURCE_SECTIONS_34.find((c) => c.id === id);
  if (!sec) throw new Error(`Source section not found: ${id}`);
  return sec;
}

/* ---------- التحقق الثابت (في وقت البناء) ---------- */
export const __VERIFY_LEDGER_34 = (() => {
  const ids = new Set<string>();
  SOURCE_SECTIONS_34.forEach((c, i) => {
    if (ids.has(c.id)) throw new Error(`duplicate ledger34 id: ${c.id}`);
    ids.add(c.id);
    if (c.order !== i + 1) throw new Error(`ledger34 order mismatch at ${c.id}`);
    if (!c.units.length) throw new Error(`empty ledger34 section: ${c.id}`);
  });
  if (SOURCE_NUMBERED_COUNT_34 !== 38) throw new Error(`expected 38 numbered sections, got ${SOURCE_NUMBERED_COUNT_34}`);
  return true;
})();

